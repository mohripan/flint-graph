"""Story package v2 saves: asset binding, server-built NOTICES and upgrade (ADR 0040).

A v2 story names its assets by SHA-256. On save, every hash must belong to an asset
of the same tenant and project that a member approved at some point; discarding an
asset later only hides it from pickers and never breaks a saved binding. The
"Asset notices" section of NOTICES is rebuilt by the server from immutable asset
fields (story asset ID, kind, SHA-256, licence, notice, source), never from names.
"""

from dataclasses import dataclass
from typing import Any, Literal
from uuid import UUID

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from flint_graph.domain.errors import DomainError
from flint_graph.infrastructure.db.models import NarrativeAsset
from flint_graph.infrastructure.narrative_artifact_store import asset_object_key

NOTICE_MARKER = (
    "=== Asset notices (generated by FlintGraph; edits below this line are replaced) ==="
)
DEFAULT_ASSET_BUDGET = 48 * 1024 * 1024


def unavailable() -> DomainError:
    return DomainError(
        409,
        "Not available yet",
        "Stage and theme (story format v2) are not enabled on this server yet.",
        "package-v2-unavailable",
    )


@dataclass(frozen=True)
class Bound:
    key: str
    kind: str
    sha256: str
    asset: NarrativeAsset


def _refused(key: str, code: str, detail: str) -> DomainError:
    location = {"code": code.replace("-", "_"), "location": f"assets.{key}"}
    return DomainError(422, "Asset not usable", detail, code, [location])


async def bind_story_assets(
    session: AsyncSession,
    *,
    tenant_id: UUID,
    project_id: UUID,
    assets: dict[str, Any],
    budget: int,
    lock: bool = True,
) -> list[Bound]:
    """Resolve each story asset to one approved library row; saves lock those rows."""
    hashes = {item["sha256"] for item in assets.values()}
    if not hashes:
        return []
    statement = (
        select(NarrativeAsset)
        .where(
            NarrativeAsset.tenant_id == tenant_id,
            NarrativeAsset.project_id == project_id,
            NarrativeAsset.sha256.in_(hashes),
            NarrativeAsset.approved_at.is_not(None),
        )
        .order_by(NarrativeAsset.created_at, NarrativeAsset.id)
    )
    rows = list(await session.scalars(statement.with_for_update() if lock else statement))
    chosen: dict[str, NarrativeAsset] = {}
    for row in rows:
        chosen.setdefault(row.sha256, row)  # The earliest approved row decides, deterministically.
    bound = []
    for key, item in sorted(assets.items()):
        match = chosen.get(item["sha256"])
        if match is None:
            raise _refused(
                key, "unknown-asset", f"“{key}” is not an approved asset of this project."
            )
        expected = (
            "image/png"
            if item["kind"] == "image"
            else "font/ttf"
            if item["path"].endswith(".ttf")
            else "font/otf"
        )
        if match.media_type != expected:
            raise _refused(key, "asset-kind", f"“{key}” does not match the kind of file it names.")
        bound.append(Bound(key, item["kind"], item["sha256"], match))
    total = sum({item.sha256: item.asset.size_bytes for item in bound}.values())
    if total > budget:
        raise _refused(
            bound[0].key,
            "asset-budget",
            "This story's assets are larger than a game can carry. "
            "Remove some or use smaller files.",
        )
    return bound


def bound_object_key(tenant_id: UUID, project_id: UUID, item: Bound) -> str:
    variant: Literal["image", "font"] = "font" if item.kind == "font" else "image"
    return asset_object_key(
        tenant_id=tenant_id, project_id=project_id, asset_id=item.asset.id, variant=variant
    )


def creator_notices(text: str) -> str:
    """The creator's own notices: anything from the generated marker on is replaced."""
    head, _, _ = text.partition(NOTICE_MARKER)
    return head.rstrip()


def _source(asset: NarrativeAsset) -> str:
    if asset.source == "uploaded":
        return "uploaded by the creator"
    provenance = asset.provenance
    return f"generated with {provenance.get('model_repo')}@{provenance.get('model_revision')}"


def compose_notices(text: str, bound: list[Bound]) -> str:
    own = creator_notices(text)
    if not bound:
        return own
    groups: dict[tuple[str, str, str], list[Bound]] = {}
    for item in bound:
        identity = (item.asset.license, _source(item.asset), (item.asset.notice or "").strip())
        groups.setdefault(identity, []).append(item)
    blocks = []
    for (license, source, notice), items in sorted(groups.items(), key=lambda pair: pair[1][0].key):
        lines = [f"{item.key} ({item.kind}, sha256 {item.sha256})" for item in items]
        lines += [f"license: {license}", f"source: {source}"]
        lines += ["  " + line for line in notice.splitlines()]
        blocks.append("\n".join(lines))
    section = NOTICE_MARKER + "\n" + "\n\n".join(blocks) + "\n"
    return f"{own}\n\n{section}" if own else section


def upgraded_story(story: dict[str, Any]) -> dict[str, Any]:
    """v1 → v2 without changing meaning; v1 per-line pictures cannot be converted."""
    if story["schema_version"] != "1":
        raise DomainError(
            409, "Already upgraded", "This story already uses stage and theme.", "conflict"
        )
    pictures = any(
        node["type"] == "line" and ("background" in node or "portrait" in node)
        for node in story["nodes"].values()
    )
    if story["assets"] or pictures:
        raise DomainError(
            409,
            "Cannot upgrade",
            "This story uses per-line pictures from the first format; "
            "move them to stage steps first.",
            "conflict",
        )
    return {**story, "schema_version": "2"}
