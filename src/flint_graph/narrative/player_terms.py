"""Player terms in a package's NOTICES (#178, ADR 0045, runtime 0.7.0).

Some voice model licenses require a game to put terms on its players. The server
writes those terms into the generated part of NOTICES, between two fixed marker
lines, exactly when a bound clip's license requires them. Every runtime finds them
the same way: only after the generated asset-notices marker, where the creator's own
text cannot reach and where uploaded asset notices are always indented. A game shows
the terms once before play and again from its menu.
"""

from flint_graph.narrative.values import PackageError

# Kept in step with application/services/narrative_package_v2.py and the runtimes.
NOTICE_MARKER = (
    "=== Asset notices (generated by FlintGraph; edits below this line are replaced) ==="
)
TERMS_BEGIN = "=== Player terms (shown once to players by the game) ==="
TERMS_END = "=== End of player terms ==="
TERMS_LIMIT = 64 * 1024


def player_terms(notices: str) -> str | None:
    """The terms a game must show its players, ``None`` when it needs none."""
    lines = notices.split("\n")
    if NOTICE_MARKER not in lines:
        return None
    generated = lines[lines.index(NOTICE_MARKER) + 1 :]
    if TERMS_BEGIN not in generated:
        if TERMS_END in generated:
            raise PackageError("invalid_notices", "NOTICES.txt")
        return None
    begin = generated.index(TERMS_BEGIN)
    rest = generated[begin + 1 :]
    if TERMS_END not in rest or TERMS_BEGIN in rest:
        raise PackageError("invalid_notices", "NOTICES.txt")
    end = rest.index(TERMS_END)
    if TERMS_END in rest[end + 1 :] or any(line.strip() for line in rest[end + 1 :]):
        raise PackageError("invalid_notices", "NOTICES.txt")
    terms = "\n".join(rest[:end]).strip("\n")
    if not terms.strip() or len(terms.encode()) > TERMS_LIMIT:
        raise PackageError("invalid_notices", "NOTICES.txt")
    return terms
